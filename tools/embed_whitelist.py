#!/usr/bin/env python3
"""One-time generation from the audited, local white_arrays.bin cache."""
import hashlib
import sys
from pathlib import Path

source = Path(sys.argv[1])
data = source.read_bytes()
expected = 'cafd0d46f189e95466cc79ed6718d15fe4988564df42ad3eab533e4a68484990'
assert hashlib.sha256(data).hexdigest() == expected, 'Unexpected whitelist cache'
assert len(data) == 2 * (1 << 20) and set(data) <= {0, 1}
target = Path(__file__).resolve().parents[1] / 'src/whitelist.hpp'
lines = ['// Generated by tools/embed_whitelist.py; do not edit.',
         '// Source: audited white_arrays.bin; SHA256: ' + expected,
         '#pragma once', '#include <array>', '#include <cstdint>', 'namespace whitelist {']
for part in range(2):
    codes = [i for i, flag in enumerate(data[part*(1<<20):(part+1)*(1<<20)]) if flag]
    assert len(codes) == 1536
    lines.append(f'inline constexpr std::array<uint32_t, 1536> part{part} = {{')
    for start in range(0, len(codes), 16):
        lines.append('    ' + ','.join(map(str, codes[start:start+16])) + ',')
    lines.append('};')
lines += ['inline constexpr const char* sha256 = "' + expected + '";', '}']
target.write_text('\n'.join(lines) + '\n')
print('Generated', target)
